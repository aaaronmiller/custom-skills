#!/usr/bin/env python3
"""Render the Markdown view of a family's ledgers and the removal-candidate list.

Usage:
  python3 -I -B render.py --ledgers DOSSIER/ledgers --page DOSSIER/version-ledger.md \
      [--title "..."] [--date YYYY-MM-DD]

Reads ledgers/file-ledger.jsonl, ledgers/idea-ledger.jsonl, ledgers/canonical.json and
ledgers/rules.json. Writes the page (frontmatter for Living Documents, then the canonical
decision, counts, the incorporation list, every idea by category, file dispositions by version
and by rule) and ledgers/removal-candidates.jsonl, the input for the separate judge. The
JSONL files stay the source of truth; the page is regenerated, never edited by hand.
"""
import argparse
import datetime as dt
import json
import os
import sys

sys.dont_write_bytecode = True
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _common import CATEGORIES, FINAL_DISPOSITIONS, read_jsonl, screen_stamp_ok, write_jsonl  # noqa: E402


def cell(s, n=220):
    s = " ".join(str(s or "").split()).replace("|", "\\|")
    return s if len(s) <= n else s[: n - 1] + "…"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--ledgers", required=True)
    ap.add_argument("--page", required=True)
    ap.add_argument("--title", default="Version idea ledger")
    ap.add_argument("--date", default=dt.date.today().isoformat())
    a = ap.parse_args()

    L = a.ledgers
    files = read_jsonl(os.path.join(L, "file-ledger.jsonl"))
    ideas = read_jsonl(os.path.join(L, "idea-ledger.jsonl"))
    canon = {}
    if os.path.exists(os.path.join(L, "canonical.json")):
        canon = json.load(open(os.path.join(L, "canonical.json"), encoding="utf-8"))
    rules = {}
    if os.path.exists(os.path.join(L, "rules.json")):
        rules = {r["id"]: r for r in json.load(open(os.path.join(L, "rules.json"), encoding="utf-8"))["rules"]}

    unscreened = [r["path"] for r in files if r.get("disposition") == "removal-candidate"
                  and not r.get("missing") and not screen_stamp_ok(r)]
    if unscreened:
        raise SystemExit(f"{len(unscreened)} removal candidates have no current screen stamp (first: "
                         f"{unscreened[0]}). Run screen_removals.py after inventory.py, then render again.")
    removal = [{"path": r["path"], "version": r.get("version"), "sha256": r["sha256"], "bytes": r.get("bytes"),
                "reason": r.get("reason"), "rule": r.get("rule"), "same_as": r.get("same_as"),
                "survivor": r.get("survivor"), "verdict": None, "judge_reason": None}
               for r in files if r.get("disposition") == "removal-candidate" and not r.get("missing")]
    held = [r for r in files if r.get("held") and not r.get("missing")]
    old = {r["path"]: r for r in read_jsonl(os.path.join(L, "removal-candidates.jsonl"))}
    for r in removal:  # keep a judge's verdict while the bytes and the survivor are unchanged
        prev = old.get(r["path"])
        if prev and prev.get("sha256") == r["sha256"] and prev.get("survivor", r["survivor"]) == r["survivor"]:
            r["verdict"], r["judge_reason"] = prev.get("verdict"), prev.get("judge_reason")
    write_jsonl(os.path.join(L, "removal-candidates.jsonl"), removal)

    out = []
    w = out.append
    w("---")
    w("id: " + os.path.splitext(os.path.basename(a.page))[0])
    w(f"title: \"{a.title}\"")
    w("type: evidence")
    w("status: active")
    w("parent: index")
    w(f"updated: {a.date}")
    w("sources: ledgers/*.jsonl (generated by version-idea-ledger render.py; edit the JSONL, not this page)")
    w("---")
    w("")
    w(f"# {a.title}")
    w("")
    w(f"Machine-readable ledgers: `{os.path.abspath(L)}/`. This page is regenerated from them.")
    w("Deletion is not part of this ledger. A separate judge confirms each removal candidate in")
    w("`removal-candidates.jsonl`, then the operator approves the exact list.")
    w("")
    if canon:
        w("## Canonical version")
        w("")
        w(f"**{canon.get('decision', '')}** at `{canon.get('canonical_root', '')}`.")
        w("")
        for r in canon.get("reasons", []):
            w(f"- {r}")
        if canon.get("candidates"):
            w("")
            w("| Version | Path | Evidence | Disposition |")
            w("|---|---|---|---|")
            for c in canon["candidates"]:
                w(f"| {cell(c.get('label'))} | `{cell(c.get('path'))}` | {cell(c.get('evidence'), 400)} | {cell(c.get('disposition'))} |")
        w("")
    w("## Counts")
    w("")
    w("| Category | Ideas |")
    w("|---|---|")
    for c in CATEGORIES:
        w(f"| {c} | {sum(1 for i in ideas if i.get('category') == c)} |")
    w(f"| **total** | **{len(ideas)}** |")
    w("")
    versions = sorted({r.get("version", "") for r in files})
    w("| Version | " + " | ".join(FINAL_DISPOSITIONS) + " | pending | files |")
    w("|---|" + "---|" * (len(FINAL_DISPOSITIONS) + 2))
    for v in versions:
        rs = [r for r in files if r.get("version") == v]
        w(f"| {v} | " + " | ".join(str(sum(1 for r in rs if r.get("disposition") == d)) for d in FINAL_DISPOSITIONS)
          + f" | {sum(1 for r in rs if r.get('disposition') == 'pending')} | {len(rs)} |")
    w(f"| **all** | " + " | ".join(str(sum(1 for r in files if r.get("disposition") == d)) for d in FINAL_DISPOSITIONS)
      + f" | {sum(1 for r in files if r.get('disposition') == 'pending')} | {len(files)} |")
    w("")
    todo = [i for i in ideas if i.get("category") == "to-incorporate"]
    w("## Incorporation list")
    w("")
    if todo:
        w("| Id | Idea | Target | Source |")
        w("|---|---|---|---|")
        for i in sorted(todo, key=lambda i: (i.get("target", ""), i["id"])):
            w(f"| {i['id']} | {cell(i.get('idea'))} | `{cell(i.get('target'), 120)}` | `{cell(i.get('source'), 120)}` {i.get('loc', '')} |")
    else:
        w("Nothing is waiting to be incorporated.")
    w("")
    w("## Ideas by category")
    for c in CATEGORIES:
        rows = [i for i in ideas if i.get("category") == c]
        if not rows:
            continue
        w("")
        w(f"### {c} ({len(rows)})")
        w("")
        extra = {"implemented": "where", "to-incorporate": "target", "duplicate": "duplicate_of",
                 "rejected": "reason", "stretch-goal": "reason", "unknown": "question"}[c]
        w(f"| Id | Version | Idea | {extra} | Source |")
        w("|---|---|---|---|---|")
        for i in sorted(rows, key=lambda i: i["id"]):
            w(f"| {i['id']} | {cell(i.get('version'), 30)} | {cell(i.get('idea'))} | {cell(i.get(extra), 160)} | "
              f"`{cell(os.path.basename(i.get('source', '')), 60)}` {cell(i.get('loc'), 30)} |")
    w("")
    w("## File dispositions by rule")
    w("")
    w("| Rule | Disposition | Files | Reason | Glob |")
    w("|---|---|---|---|---|")
    by_rule = {}
    for r in files:
        by_rule.setdefault(r.get("rule") or "(none)", []).append(r)
    for rid in sorted(by_rule):
        rs = by_rule[rid]
        rule = rules.get(rid, {})
        disp = ", ".join(sorted({r.get("disposition", "") for r in rs}))
        w(f"| {rid} | {disp} | {len(rs)} | {cell(rule.get('reason') or rs[0].get('reason'), 260)} | `{cell(rule.get('glob', ''), 120)}` |")
    w("")
    w(f"## Removal candidates ({len(removal)})")
    w("")
    w("Classified only. Nothing here has been deleted. Each passed the removal screen and names the")
    w("surviving copy of its bytes. Input for the judge: `ledgers/removal-candidates.jsonl`.")
    w("")
    if removal:
        w("| Path | Bytes | Survivor | Reason | Verdict |")
        w("|---|---|---|---|---|")
        for r in removal:
            s = r.get("survivor") or {}
            where = f"{len(s['members'])} archive members" if s.get("kind") == "members" else \
                f"{s.get('kind')}: `{cell(s.get('tree_path') or s.get('path'), 120)}`"
            w(f"| `{cell(r['path'], 160)}` | {r.get('bytes')} | {where} | {cell(r.get('reason'), 140)} | "
              f"{r.get('verdict') or 'awaiting judge'} |")
    w("")
    w(f"## Held by the removal screen ({len(held)})")
    w("")
    w("A rule proposed these for removal; the screen kept them as `archive`. Codes: H1 stale, H2 cited")
    w("by an idea, H3 protected class, H4 bytes survive nowhere else, H5 archive with exclusive members.")
    w("")
    if held:
        w("| Path | Rule | Held because |")
        w("|---|---|---|")
        for r in held:
            w(f"| `{cell(r['path'], 160)}` | {r.get('rule')} | {cell('; '.join(r['held']), 300)} |")
    w("")
    os.makedirs(os.path.dirname(os.path.abspath(a.page)), exist_ok=True)
    with open(a.page, "w", encoding="utf-8") as fh:
        fh.write("\n".join(out))
    print(f"wrote {a.page} ({len(ideas)} ideas, {len(files)} files, {len(removal)} removal candidates)")


if __name__ == "__main__":
    main()
